"""Native Authentication Verification (Design §8, §15, §16, §17).

Implements bounded, deterministic runtime verification for the Authentication area:
- A1: unauthenticated access to protected route (anonymous GET)
- A2: invalid authentication attempt (synthetic invalid secret POST login)
- A3: valid authentication positive control for each declared actor (POST login)
- A4: authenticated access to protected route for primary user (GET)
- A5: logout operation (POST/GET logout)
- A6: reuse of invalidated session after logout (GET protected route)

Guarantees:
- Synthetic identities only (generated by IdentityVault; never real credentials).
- No brute-force, password-spraying, or account enumeration.
- Exactly 1 invalid attempt (A2) and 1 login attempt per declared actor (A3).
- Strictly bounded request count (max 9 requests per run).
- Response classification: allowed, denied, ambiguous, incomplete.
- Evidence records match Design §15 schema (check, actors, method, path, status,
  classification, marker_present, elapsed_ms, fingerprint).
- Deterministic findings RT-AUTH-001, RT-AUTH-002, RT-AUTH-003 with severity HIGH.
- Positive control failure makes the area INCOMPLETE with no findings emitted.
- If logout is not declared, the area can at most be EXECUTED, not PASS.
- Secrets never exposed in findings, evidence, representations, or reports.
"""

